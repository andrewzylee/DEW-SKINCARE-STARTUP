// Runtime registry for community-added products so getProduct resolves them everywhere
// (product page, shelf, ranking) — the store hydrates this from localStorage on load.
const customRegistry = new Map<string, Product>();
export function registerCustomProducts(list: Product[]): void {
  for (const p of list) customRegistry.set(p.id, p);
}

export const getProduct = (id: string): Product | undefined =>
  catalog.find((p) => p.id === id) ?? customRegistry.get(id);

// ---------- DOMAIN & CATEGORY HELPERS ----------
// Ordered so routines/rankings read top-of-face → base → color, like a shelf.
export const SKINCARE_CATEGORIES: SkincareCategory[] = [
  'cleanser',
  'serum',
  'treatment',
  'moisturizer',
  'spf',
];
export const MAKEUP_CATEGORIES: MakeupCategory[] = [
  'foundation',
  'concealer',
  'blush',
  'bronzer',
  'lip',
  'eyeshadow',
  'eyeliner',
  'mascara',
  'brow',
  'setting',
  'nail',
];
export const FRAGRANCE_CATEGORIES: FragranceCategory[] = ['fragrance'];
const MAKEUP_SET = new Set<Category>(MAKEUP_CATEGORIES);
const FRAGRANCE_SET = new Set<Category>(FRAGRANCE_CATEGORIES);

export const categoryDomain = (c: Category): Domain =>
  FRAGRANCE_SET.has(c) ? 'fragrance' : MAKEUP_SET.has(c) ? 'makeup' : 'skincare';
// Domain of a product — explicit `domain` wins; otherwise inferred from its category.
export const productDomain = (p: Product): Domain => p.domain ?? categoryDomain(p.category);

export const skincareCatalog = catalog.filter((p) => productDomain(p) === 'skincare');
export const makeupCatalog = catalog.filter((p) => productDomain(p) === 'makeup');
export const fragranceCatalog = catalog.filter((p) => productDomain(p) === 'fragrance');
export const catalogForDomain = (d: Domain) =>
  d === 'makeup' ? makeupCatalog : d === 'fragrance' ? fragranceCatalog : skincareCatalog;
export const categoriesForDomain = (d: Domain): Category[] =>
  d === 'makeup' ? MAKEUP_CATEGORIES : d === 'fragrance' ? FRAGRANCE_CATEGORIES : SKINCARE_CATEGORIES;
