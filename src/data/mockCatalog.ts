export type SkinType = 'oily' | 'combination' | 'dry' | 'sensitive';
// Shade phenotype — powers Shade Match (the acquisition wedge) and "people with your skin".
export type Tone = 'fair' | 'light' | 'medium' | 'tan' | 'deep';
export type Undertone = 'cool' | 'neutral' | 'warm';
export const TONES: Tone[] = ['fair', 'light', 'medium', 'tan', 'deep'];
export const UNDERTONES: Undertone[] = ['cool', 'neutral', 'warm'];
export type Domain = 'skincare' | 'makeup' | 'fragrance';
export type SkincareCategory = 'cleanser' | 'treatment' | 'moisturizer' | 'spf' | 'serum';
export type MakeupCategory =
  | 'foundation'
  | 'concealer'
  | 'blush'
  | 'bronzer'
  | 'lip'
  | 'eyeshadow'
  | 'eyeliner'
  | 'mascara'
  | 'brow'
  | 'setting'
  | 'nail';
// Fragrance is one rankable category (you rank all your scents against each other, Beli-style).
export type FragranceCategory = 'fragrance';
export type Category = SkincareCategory | MakeupCategory | FragranceCategory;
// Scent family — fragrance's analog of a skincare concern or a makeup finish.
export type ScentFamily =
  | 'fresh'
  | 'citrus'
  | 'woody'
  | 'floral'
  | 'gourmand'
  | 'amber'
  | 'aquatic'
  | 'spicy';
export type Concern = 'acne' | 'oil' | 'texture' | 'darkspots' | 'starter';
export type PriceTier = '$' | '$$' | '$$$';
export type TimeOfDay = 'am' | 'pm' | 'any';
// Makeup "finish" — the makeup analog of a skincare claim.
export type Finish = 'dewy' | 'glowy' | 'natural' | 'satin' | 'matte';

// Extends the Product type in the spec with `timeOfDay` (used by the stack generator
// to place actives in the correct AM/PM routine — e.g. Vitamin C in AM, retinoids in PM),
// and with makeup fields (`domain`, `finish`, `styleTags`) so both domains share one shape.
export interface Product {
  id: string;
  name: string;
  brand: string;
  category: Category;
  skinTypes: SkinType[]; // skincare: who it's for. makeup: all types (universal).
  concernTags: Concern[]; // skincare only; [] for makeup
  priceTier: PriceTier;
  price: number;
  timeOfDay: TimeOfDay;
  blurb: string; // the one-line "why"
  restockUrl: string; // stub — placeholder, no real commerce
  domain?: Domain; // defaults to 'skincare' (see productDomain) — makeup/fragrance items set this
  finish?: Finish; // makeup only
  scentFamily?: ScentFamily; // fragrance only
  notes?: string[]; // fragrance only — top/heart/base notes for display
  styleTags?: string[]; // taste descriptors (e.g. 'clean','glowy','bold') → taste archetype
  image?: string; // optional real product photo (URL or /public path). Falls back to a
  // monogram tile. You can also just drop files into src/assets/products/<id>.jpg — see
  // src/lib/productImages.ts.
  custom?: boolean; // community-added on-device (provisional) — behaves like any product
}

