#!/usr/bin/env node
/**
 * Generates supabase/seed/catalog.sql from the app's catalog.
 *
 * Why this exists: rankings.product_id has a foreign key to products, but the hand-written seed
 * only ever contained 27 of the 1,164 catalog rows. Ranking any of the other ~1,137 products
 * fails with FK 23503 — and the client discards the error, so the shelf silently empties on the
 * next launch. The seed has to cover the whole catalog or the app is broken for real users.
 *
 * Source of truth is mobile/src/core/catalog-full.generated.ts, which is verified id-for-id
 * identical to the web reference's five data files.
 *
 *   node scripts/generate-catalog-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'mobile', 'src', 'core', 'catalog-full.generated.ts');
const OUT = join(root, 'supabase', 'seed', 'catalog.sql');

const text = readFileSync(SRC, 'utf8');
const start = text.indexOf('[', text.indexOf('fullCatalog'));
const end = text.lastIndexOf('];');
if (start < 0 || end < 0) throw new Error('Could not locate the fullCatalog array literal.');

// The file is generated and contains only object literals — evaluating it is how we avoid
// hand-rolling a TypeScript parser for what is really just data.
const products = eval(`(${text.slice(start, end + 1)})`);
if (!Array.isArray(products) || products.length === 0) throw new Error('Parsed catalog is empty.');

const TIME_OF_DAY = new Set(['am', 'pm', 'any']);

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const qOrNull = (v) => (v === undefined || v === null || v === '' ? 'null' : q(v));
const numOrNull = (v) => (typeof v === 'number' && Number.isFinite(v) ? v : 'null');
const tags = (v) => (Array.isArray(v) && v.length ? `array[${v.map(q).join(',')}]::text[]` : `'{}'::text[]`);

const seen = new Set();
const rows = [];
for (const p of products) {
  if (!p?.id || seen.has(p.id)) continue; // a duplicate id would abort the whole insert
  seen.add(p.id);
  const tod = TIME_OF_DAY.has(p.timeOfDay) ? p.timeOfDay : 'any';
  rows.push(
    `  (${q(p.id)}, ${q(p.brand)}, ${q(p.name)}, ${q(p.category)}, ${q(p.domain ?? 'skincare')}, ` +
      `${numOrNull(p.price)}, ${q(tod)}::time_of_day, ${qOrNull(p.image)}, ${qOrNull(p.blurb)}, ${tags(p.styleTags)})`,
  );
}

const sql = `-- Dew — full catalog seed (${rows.length} products). GENERATED by scripts/generate-catalog-seed.mjs.
-- Do not edit by hand; re-run the script instead.
--
-- Idempotent: re-running updates existing rows rather than failing on the primary key, so this is
-- safe to paste again after a catalog change.

insert into public.products
  (id, brand, name, category, domain, price, time_of_day, image_url, blurb, style_tags)
values
${rows.join(',\n')}
on conflict (id) do update set
  brand       = excluded.brand,
  name        = excluded.name,
  category    = excluded.category,
  domain      = excluded.domain,
  price       = excluded.price,
  time_of_day = excluded.time_of_day,
  image_url   = excluded.image_url,
  blurb       = excluded.blurb,
  style_tags  = excluded.style_tags;
`;

writeFileSync(OUT, sql, 'utf8');
const domains = products.reduce((a, p) => ((a[p.domain ?? 'skincare'] = (a[p.domain ?? 'skincare'] ?? 0) + 1), a), {});
console.log(`Wrote ${OUT}`);
console.log(`  ${rows.length} products  (${(sql.length / 1024).toFixed(0)} KB)`);
console.log(`  by domain: ${Object.entries(domains).map(([k, v]) => `${k} ${v}`).join(', ')}`);
console.log(`  with images: ${products.filter((p) => p.image).length}`);
